const rows = [];
function group(category, entries) {
  const defaults = categories.find((c) => c.id === category).sources;
  for (const [
    id,
    title,
    question,
    criteria,
    preparation,
    sources = [],
    priority = "normal",
  ] of entries) {
    rows.push({
      id,
      category,
      title,
      question,
      criteria: criteria.split("｜"),
      preparation,
      sources: [...new Set([...defaults, ...sources])],
      priority,
    });
  }
}

